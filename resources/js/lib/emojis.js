const EMOJI_ONLY_REGEX = /^[\s\p{Extended_Pictographic}\u200D\uFE0F\u{1F3FB}-\u{1F3FF}]+$/u;
const CONTAINS_EMOJI_REGEX = /\p{Extended_Pictographic}/u;

export function isEmojiOnlyText(text) {
    if (!text || typeof text !== 'string') return false;
    const trimmed = text.trim();
    if (!trimmed || trimmed.length > 30) return false;
    return EMOJI_ONLY_REGEX.test(trimmed) && CONTAINS_EMOJI_REGEX.test(trimmed);
}
